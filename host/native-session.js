/** Public DSH session observation and per-Bot model/input configuration. */
import { Buffer } from 'node:buffer';
import { newId } from './util.js';

/** Observe without activating, repairing, or taking ownership of the log. */
export async function inspectSessionHeader(ctx, sessionId) {
  const query = ctx.get('sessionQuery');
  if (!query || typeof query.observeSession !== 'function') {
    throw new Error('Bot Team requires sessionQuery.observeSession for safe native session recovery');
  }
  let observation;
  try {
    observation = await query.observeSession(sessionId, { projectionMode: 'none' });
    if (!observation.header || observation.header.id !== sessionId || typeof observation.header.cwd !== 'string') {
      throw new Error('Invalid stored Bot session header: ' + sessionId);
    }
    return { ...observation.header };
  } catch (error) {
    // Corruption, writer ownership, cancellation, permission, and I/O failures
    // must reach the caller. Only this typed absence allows first creation.
    if (error?.code === 'SESSION_QUERY_SESSION_NOT_FOUND') return undefined;
    throw error;
  } finally {
    observation?.[Symbol.dispose]?.();
  }
}

export function botModel(bot) {
  return {
    provider: bot.provider,
    model: bot.model,
    ...(typeof bot.reasoningEffort === 'string' && bot.reasoningEffort ? { reasoningEffort: bot.reasoningEffort } : {}),
    ...(Number.isInteger(bot.maxTokens) && bot.maxTokens > 0 ? { maxTokens: bot.maxTokens } : {}),
  };
}

/**
 * Outermost scoped waterfalls win AFTER the native preset/model listeners.
 * Snapshot once per assembly so a Bot edit cannot split prompt and request
 * routing. Explicit subject checks leave native subagent model choices intact.
 */
export async function installBotModel(ctx, agentCtx, agent, currentBot, publishSelection, retain, assertCurrent = () => {}) {
  const llm = ctx.get('llm');
  if (typeof llm?.resolveCallConfig !== 'function') throw new Error('Native Bot model validation is unavailable');
  let assembled;
  let normalized;
  let normalizedKey;
  const readSelection = async () => {
    assertCurrent();
    const requested = botModel(await currentBot());
    assertCurrent();
    const key = JSON.stringify(requested);
    if (key === normalizedKey) return normalized;
    // Resolve the same canonical reasoning value used by native selectModel,
    // so modelSelection.pending is consumed by the actual request/header.
    const resolved = await llm.resolveCallConfig(requested);
    assertCurrent();
    normalized = {
      provider: resolved.provider, model: resolved.model,
      ...(resolved.reasoningEffort === undefined ? {} : { reasoningEffort: resolved.reasoningEffort }),
      ...(requested.maxTokens === undefined ? {} : { maxTokens: requested.maxTokens }),
    };
    normalizedKey = key;
    return normalized;
  };
  const initial = await readSelection();
  assertCurrent();
  publishSelection(initial);
  retain(agentCtx.on('system-prompt/assemble', async (_assembly, context, next) => {
    if (context.agent !== agent) return next();
    const selected = await readSelection();
    publishSelection(selected);
    const result = await next();
    assertCurrent();
    assembled = selected;
    return { ...result, variables: { ...result.variables, provider: selected.provider, model: selected.model } };
  }, { prepend: true }));
  retain(agentCtx.on('agent/request', async (payload, next) => {
    if (payload.agent !== agent) return next();
    assertCurrent();
    const selected = assembled || await readSelection();
    assertCurrent();
    const result = await next();
    assertCurrent();
    const { reasoningEffort, maxTokens, ...rest } = result;
    return { ...rest, ...selected };
  }, { prepend: true }));
  // Native model selection retains a private execution cache. We deliberately
  // do not call selectModel (which also writes the deployment default). Replace
  // only its generated route notice with the route actually selected above.
  retain(agentCtx.on('agent/pre-step', async (payload, next) => {
    const decision = await next();
    if (payload.agent !== agent || decision.kind === 'reject' || payload.signal?.aborted) return decision;
    assertCurrent();
    if (decision.messages.length === 0 && (payload.step === 1 || payload.messages.length > 0)) return decision;
    const messages = decision.messages.filter(message => message.source?.kind !== 'model-selection');
    const previous = agent.session.requestHeader?.()?.config;
    const selected = assembled;
    if (selected && previous && (previous.provider !== selected.provider || previous.model !== selected.model)) {
      messages.push({
        role: 'user', id: newId('umsg'),
        content: [{ type: 'text', text: '[model changed: assistant turns above this point were generated by ' + previous.provider + '/' + previous.model + '; the session continues with ' + selected.provider + '/' + selected.model + ']' }],
        source: { kind: 'model-selection', form: 'notice', summary: previous.provider + '/' + previous.model + ' → ' + selected.provider + '/' + selected.model },
      });
    }
    return { ...decision, messages };
  }, { prepend: true }));
}

/** Preserve the complete input identity/source required by inbox correlation. */
export async function submitNativeInput(ctx, agent, input, selection, assertCurrent = () => {}) {
  assertCurrent();
  if (!input || input.role !== 'user' || !input.id || !input.source || !Array.isArray(input.content)) {
    throw new Error('Bot input must be a complete native UserMessage');
  }
  let content = input.content;
  if (content.some(part => part.type !== 'text')) {
    const attachments = ctx.get('attachments');
    if (typeof attachments?.admitPromptContent !== 'function') throw new Error('Native attachment admission is unavailable');
    if (content.some(part => part.type === 'image')) {
      const llm = ctx.get('llm');
      if (typeof llm?.resolveModelInfo !== 'function') throw new Error('Native image model validation is unavailable');
      const model = await llm.resolveModelInfo(selection.provider, selection.model);
      assertCurrent();
      if (model.inputModalities && !model.inputModalities.includes('image')) throw new Error('Bot model does not support image input');
      // The admission API takes encoded images, whereas Bot history can already
      // hold durable references. Re-admit their verified bytes as one batch so
      // native count, size, format, and storage checks still apply.
      content = await Promise.all(content.map(async part => {
        if (part.type !== 'image' || !part.attachment) return part;
        const stored = await attachments.readImage(part.attachment);
        assertCurrent();
        return { type: 'image', mediaType: stored.ref.mediaType, data: Buffer.from(stored.data).toString('base64') };
      }));
      assertCurrent();
    }
    content = await attachments.admitPromptContent(content);
    assertCurrent();
  }
  assertCurrent();
  if (ctx.agents.get(agent.id) !== agent) throw new Error('Bot session was disposed during input admission');
  await agent.followup({ ...input, content });
  assertCurrent();
}
